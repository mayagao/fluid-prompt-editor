// Get icon by category type
export const getCategoryIcon = (category: string) => {
  switch (category?.toLowerCase()) {
    case "issues":
      return <IssueIcon />;
    case "pull requests":
    case "prs":
      return <PullRequestIcon />;
    case "discussions":
      return <DiscussionIcon />;
    case "codebase":
      return <CodebaseIcon />;
    default:
      return <CodebaseIcon />;
  }
};
